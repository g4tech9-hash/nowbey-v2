#!/usr/bin/env bash
# Wires up the local stack the live suites (npm run test:local / test:ui / test:fuzz) expect:
#   * a throwaway Postgres on 127.0.0.1:55432, database "nowbey", schema pushed from src/db/schema.ts
#     and seeded by src/db/seed.sql (pass PG_BIN=/path/to/postgres/bin if postgres is not on PATH)
#   * a self-signed certificate for "localhost", trusted by the app through NODE_EXTRA_CA_CERTS
#   * the SMTP catcher (tests/harness/smtp-capture.py) on 4465, writing to /tmp/nowbey-mail
#   * .env.local with test-only values (never real secrets), then `npm run dev` on port 3000
#
# Nothing here touches production. Usage:
#   bash tests/run-local.sh            # start everything, leave the dev server in the foreground
#   bash tests/run-local.sh --no-dev   # prepare database, mail and .env.local only
set -euo pipefail
cd "$(dirname "$0")/.."

PGPORT="${PGPORT:-55432}"
PGDATA="${PGDATA:-/tmp/nowbey-pg}"
CERTS=/tmp/nowbey-certs
MAIL_DIR=/tmp/nowbey-mail
PG_BIN="${PG_BIN:-$(dirname "$(command -v postgres 2>/dev/null || echo /usr/lib/postgresql/16/bin/postgres)")}"
DB_URL="postgresql://postgres@127.0.0.1:${PGPORT}/nowbey"

if ! (exec 3<>"/dev/tcp/127.0.0.1/${PGPORT}") 2>/dev/null; then
  if [ ! -f "$PGDATA/PG_VERSION" ]; then "$PG_BIN/initdb" -D "$PGDATA" -U postgres --auth=trust >/dev/null; fi
  "$PG_BIN/pg_ctl" -D "$PGDATA" -o "-p ${PGPORT} -k /tmp" -l /tmp/nowbey-pg.log -w start >/dev/null
fi
node -e '
  const pg = require("pg");
  const c = new pg.Client({ connectionString: process.argv[1].replace(/\/nowbey$/, "/postgres") });
  c.connect().then(() => c.query("create database nowbey")).catch(() => {}).finally(() => c.end());
' "$DB_URL"

mkdir -p "$CERTS" "$MAIL_DIR"
if [ ! -f "$CERTS/cert.pem" ]; then
  openssl req -x509 -newkey rsa:2048 -nodes -days 30 -subj "/CN=localhost" \
    -addext "subjectAltName=DNS:localhost,IP:127.0.0.1" \
    -keyout "$CERTS/key.pem" -out "$CERTS/cert.pem" >/dev/null 2>&1
fi
if ! (exec 3<>/dev/tcp/127.0.0.1/4465) 2>/dev/null; then
  nohup python3 tests/harness/smtp-capture.py --port 4465 --cert "$CERTS/cert.pem" --key "$CERTS/key.pem" \
    --out "$MAIL_DIR" >/tmp/nowbey-smtp.log 2>&1 &
fi

if [ ! -f .env.local ] || grep -q "^# generated by tests/run-local.sh" .env.local; then
  cat > .env.local <<EOF
# generated by tests/run-local.sh — test-only values, safe to delete
DATABASE_URL=${DB_URL}
APP_URL=http://localhost:3000
AUTH_SECRET=local-test-secret-not-for-production-0123456789
CRON_SECRET=local-cron-secret-0123456789
ADMIN_HANDLES=mario242,eastsiderick
ADMIN_EMAILS=@example.test
SMTP_HOST=localhost
SMTP_PORT=4465
SMTP_USER=catcher
SMTP_PASS=catcher
MAIL_FROM=NowBey <alerts@nowbey.test>
GOOGLE_CLIENT_ID=test-client.apps.googleusercontent.com
GOOGLE_CLIENT_SECRET=GOCSPX-test-secret
GOOGLE_OAUTH_BASE=http://127.0.0.1:4466
NEXT_PUBLIC_LAUNCH_STAGE=nassau
EOF
fi

DATABASE_URL="$DB_URL" npx drizzle-kit push --force >/tmp/nowbey-push.log 2>&1 || { cat /tmp/nowbey-push.log; exit 1; }
node -e '
  const pg = require("pg"); const fs = require("fs");
  const c = new pg.Client({ connectionString: process.argv[1] });
  c.connect().then(() => c.query(fs.readFileSync("src/db/seed.sql", "utf8"))).catch((e) => console.error("seed:", e.message)).finally(() => c.end());
' "$DB_URL"
for f in src/db/add-security-fixes.sql; do
  [ -f "$f" ] && DATABASE_URL="$DB_URL" node -e '
    const pg = require("pg"); const fs = require("fs");
    const c = new pg.Client({ connectionString: process.env.DATABASE_URL });
    c.connect().then(() => c.query(fs.readFileSync(process.argv[1], "utf8"))).finally(() => c.end());
  ' "$f"
done

echo "local stack ready: db ${DB_URL}, smtp :4465 -> ${MAIL_DIR}"
if [ "${1:-}" != "--no-dev" ]; then
  NODE_EXTRA_CA_CERTS="$CERTS/cert.pem" exec npm run dev
fi
