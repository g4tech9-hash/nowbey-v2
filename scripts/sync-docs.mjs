#!/usr/bin/env node
/**
 * Keeps `docs/FEATURES.md` in step with `src/content/featureRegistry.ts`.
 *
 * The registry is the single source of truth for what the product can do and which
 * module implements it. This script bundles that registry with esbuild, checks it, and
 * writes the markdown reference from it. Nothing in `docs/FEATURES.md` is typed by hand,
 * so the documentation cannot describe a feature the code does not have - or quietly lose
 * one that it does.
 *
 *   node scripts/sync-docs.mjs           write docs/FEATURES.md if it changed
 *   node scripts/sync-docs.mjs --check   fail if docs/FEATURES.md is out of date
 *
 * It exits non-zero when the registry is broken, so a broken registry fails the build
 * instead of shipping a landing page that lies.
 */

import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { build } from "esbuild";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..");
const REGISTRY = path.join(ROOT, "src", "content", "featureRegistry.ts");
const OUTPUT = path.join(ROOT, "docs", "FEATURES.md");

/** The check is a build-time gate, so anything that throws is a failure worth a stack. */
const problems = [];

/** Escapes the characters that would break a markdown table cell. */
function cell(value) {
  return String(value).replace(/\|/g, "\\|").replace(/\r?\n/g, " ").trim();
}

/** Loads the registry by bundling it with esbuild, so the script never needs a TypeScript loader. */
async function loadRegistry() {
  const result = await build({
    entryPoints: [REGISTRY],
    bundle: true,
    write: false,
    format: "esm",
    platform: "node",
    target: "node20",
    logLevel: "silent",
  });
  const bundled = result.outputFiles[0].text;

  const temporary = path.join(os.tmpdir(), `nowbey-features-${process.pid}.mjs`);
  await writeFile(temporary, bundled, "utf8");
  try {
    return await import(pathToFileURL(temporary).href);
  } finally {
    await rm(temporary, { force: true });
  }
}

/** Checks the registry the way the page uses it, so a broken entry cannot reach production. */
function validate(registry) {
  const { FEATURES, FEATURE_CATEGORIES, FEATURE_STATUS_LABELS } = registry;
  if (!Array.isArray(FEATURES) || FEATURES.length === 0) {
    problems.push("FEATURES is empty or is not an array.");
    return;
  }
  const categoryKeys = new Set(FEATURE_CATEGORIES.map((category) => category.key));
  const seen = new Set();

  for (const feature of FEATURES) {
    const where = feature.id || feature.name || "(unnamed feature)";
    for (const field of ["id", "name", "summary", "category", "status", "source"]) {
      if (!feature[field]) problems.push(`${where}: the field "${field}" is empty.`);
    }
    if (!Array.isArray(feature.capabilities) || feature.capabilities.length === 0) {
      problems.push(`${where}: capabilities must be a non-empty list.`);
    }
    if (feature.metric && (!feature.metric.label || !feature.metric.value)) {
      problems.push(`${where}: the metric needs both a label and a value.`);
    }
    if (seen.has(feature.id)) problems.push(`${where}: the id is used twice.`);
    seen.add(feature.id);
    if (!categoryKeys.has(feature.category)) {
      problems.push(`${where}: "${feature.category}" is not a declared category.`);
    }
    if (!FEATURE_STATUS_LABELS[feature.status]) {
      problems.push(`${where}: "${feature.status}" is not a declared status.`);
    }
    if (feature.source && !feature.source.startsWith("src/lib/")) {
      problems.push(`${where}: the source must be a path under src/lib/ (got "${feature.source}").`);
    }
    if (feature.source && !existsSync(path.join(ROOT, feature.source))) {
      problems.push(`${where}: ${feature.source} does not exist.`);
    }
  }
}

/** Renders the markdown reference from the registry. */
function render(registry) {
  const { FEATURES, FEATURE_CATEGORIES, FEATURE_STATUS_LABELS, featureCensus } = registry;
  const census = featureCensus(FEATURES);
  const lines = [];

  lines.push("# Feature registry");
  lines.push("");
  lines.push(
    "<!-- Generated by `node scripts/sync-docs.mjs` from `src/content/featureRegistry.ts`. Do not edit this file by hand: the next build overwrites it. Edit the registry instead. -->",
  );
  lines.push("");
  lines.push(
    "Every capability of NowBey, the module that implements it, and how real it is. The same registry renders the feature cards on the landing page, so this document and the page cannot disagree.",
  );
  lines.push("");
  lines.push(`**${census.total} features** - ${census.live} live, ${census.beta} beta, ${census.planned} planned, ${census.internal} internal.`);
  lines.push("");

  lines.push("| Feature | Category | Status | Implemented in |");
  lines.push("| --- | --- | --- | --- |");
  for (const feature of FEATURES) {
    const category = FEATURE_CATEGORIES.find((entry) => entry.key === feature.category);
    lines.push(
      `| [${cell(feature.name)}](#${feature.id}) | ${cell(category ? category.label : feature.category)} | ${cell(
        FEATURE_STATUS_LABELS[feature.status],
      )} | \`${cell(feature.source)}\` |`,
    );
  }
  lines.push("");

  for (const category of FEATURE_CATEGORIES) {
    const inCategory = FEATURES.filter((feature) => feature.category === category.key);
    if (inCategory.length === 0) continue;
    lines.push(`## ${category.label}`);
    lines.push("");
    lines.push(category.blurb);
    lines.push("");

    for (const feature of inCategory) {
      lines.push(`### ${feature.name}`);
      lines.push("");
      lines.push(`<a id="${feature.id}"></a>`);
      lines.push("");
      lines.push(feature.summary);
      lines.push("");
      lines.push(`- **Status:** ${FEATURE_STATUS_LABELS[feature.status]}`);
      lines.push(`- **Implemented in:** \`${feature.source}\``);
      if (feature.metric) {
        lines.push(`- **${feature.metric.label}:** ${feature.metric.value}`);
      }
      lines.push("");
      lines.push("What it does:");
      lines.push("");
      for (const capability of feature.capabilities) {
        lines.push(`- ${capability}`);
      }
      lines.push("");
    }
  }

  return `${lines.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd()}\n`;
}

async function main() {
  const check = process.argv.includes("--check");
  const registry = await loadRegistry();
  validate(registry);

  if (problems.length > 0) {
    console.error("The feature registry is broken:");
    for (const problem of problems) console.error(`  - ${problem}`);
    process.exit(1);
  }

  const markdown = render(registry);
  const existing = existsSync(OUTPUT) ? await readFile(OUTPUT, "utf8") : null;

  if (existing === markdown) {
    console.log(`docs/FEATURES.md is up to date (${registry.FEATURES.length} features).`);
    return;
  }

  if (check) {
    console.error("docs/FEATURES.md is out of date. Run `npm run sync-docs` and commit the result.");
    process.exit(1);
  }

  await mkdir(path.dirname(OUTPUT), { recursive: true });
  await writeFile(OUTPUT, markdown, "utf8");
  console.log(
    `docs/FEATURES.md written from src/content/featureRegistry.ts (${registry.FEATURES.length} features, ${registry.FEATURE_CATEGORIES.length} categories).`,
  );
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
